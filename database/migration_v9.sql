CREATE TABLE IF NOT EXISTS interview_recordings (
  id CHAR(36) PRIMARY KEY,
  interview_id BIGINT UNSIGNED NOT NULL,
  egress_id VARCHAR(90) NULL,
  object_key VARCHAR(240) NOT NULL,
  storage_id CHAR(64) NOT NULL,
  state ENUM('WAITING','STARTING','RECORDING','STOPPING','PROCESSING','COMPLETE','FAILED','CANCELLED','DELETING','DELETED') NOT NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  created_at DATETIME NOT NULL,
  policy JSON NOT NULL,
  requested_at DATETIME NULL,
  stop_requested_at DATETIME NULL,
  egress_ended_at DATETIME NULL,
  started_at DATETIME NULL,
  saved_at DATETIME NULL,
  expires_at DATETIME NULL,
  size_bytes BIGINT UNSIGNED NULL,
  duration_seconds INT UNSIGNED NULL,
  format VARCHAR(12) NOT NULL DEFAULT 'mp4',
  failure_reason VARCHAR(240) NULL,
  hold_reason VARCHAR(240) NULL,
  hold_by BIGINT UNSIGNED NULL,
  hold_at DATETIME NULL,
  delete_requested_by BIGINT UNSIGNED NULL,
  deleted_at DATETIME NULL,
  transcription_state VARCHAR(30) NOT NULL DEFAULT 'NOT_STARTED',
  summary_task_id VARCHAR(100) NULL,
  UNIQUE KEY uk_recording_interview (interview_id),
  UNIQUE KEY uk_recording_egress (egress_id),
  UNIQUE KEY uk_recording_key (object_key),
  KEY idx_recording_lifecycle (state, expires_at),
  CONSTRAINT fk_recording_interview FOREIGN KEY (interview_id) REFERENCES interviews(id),
  CONSTRAINT fk_recording_creator FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS interview_recording_consents (
  id BIGINT UNSIGNED PRIMARY KEY,
  recording_id CHAR(36) NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  decision ENUM('ACCEPTED','DECLINED') NOT NULL,
  decided_at DATETIME NOT NULL,
  KEY idx_recording_consent (recording_id, user_id, id),
  CONSTRAINT fk_consent_recording FOREIGN KEY (recording_id) REFERENCES interview_recordings(id),
  CONSTRAINT fk_consent_user FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
